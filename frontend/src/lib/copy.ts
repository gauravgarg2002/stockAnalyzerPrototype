/** Replace {name} placeholders. Unknown placeholders are left as they are. */
export function fill(template: string, values: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (whole, key: string) => (key in values ? (values[key] as string) : whole));
}

/** Every string in `copy`, flattened, for tests. */
export function allCopyStrings(node: unknown = copy, path = 'copy'): Array<{ path: string; text: string }> {
  if (typeof node === 'string') return [{ path, text: node }];
  if (node && typeof node === 'object') {
    return Object.entries(node as Record<string, unknown>).flatMap(([k, v]) => allCopyStrings(v, `${path}.${k}`));
  }
  return [];
}
